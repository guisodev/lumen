const DICTS = { en: EN, pt: PT, fr: FR };

function setLang(lang) {
  LANG = lang in DICTS ? lang : 'es';
  document.documentElement.lang = LANG;
}

function t(es, vars) {
  let s = (DICTS[LANG] && DICTS[LANG][es]) || es;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
  return s;
}

// Traduce los textos fijos del HTML (nodos de texto y atributos visibles).
function translateDom(root = document.body) {
  const dict = DICTS[LANG];
  if (!dict) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const raw = node.nodeValue;
    const key = raw.trim();
    if (key && dict[key]) node.nodeValue = raw.replace(key, dict[key]);
  }
  for (const attr of ['title', 'placeholder', 'aria-label']) {
    root.querySelectorAll(`[${attr}]`).forEach((el) => {
      const v = el.getAttribute(attr);
      if (dict[v]) el.setAttribute(attr, dict[v]);
    });
  }
  document.title = t(document.title);
}
